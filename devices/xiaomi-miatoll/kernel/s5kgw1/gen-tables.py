#!/usr/bin/env python3
"""gen-tables.py com.qti.sensormodule.sunny_s5kgw1.bin > s5kgw1-tables.h: the S5KGW1's registers.

The input is Xiaomi's own sensor module for the Redmi Note 9 Pro (miatoll), from
its vendor partition, as LineageOS keeps it:
  https://github.com/TheMuppets/proprietary_vendor_xiaomi_miatoll  (lineage-22.2)
  proprietary/vendor/lib64/camera/com.qti.sensormodule.sunny_s5kgw1.bin
(the ofilm_ one has the same registers). These are the settings Android runs
this very module with, on this SoC's 19.2 MHz camera clock.

Samsung's own tables for the GW1 (the Exynos 9611 kernel's fimc-is-cis-gw1-set*.h,
26 MHz) were tried first, with the PLLs recalculated: the sensor took them and never
made a frame (frame count 0xff, vendor error 0x0100 at 0x3000), then stopped
answering. This phone's GW1 reads revision 0xA2 with 0x90, 0x03 at 0x0D/0x0E;
Samsung's are for 0x90, 0x13.

The file is the output of Qualcomm's Chromatix parameter parser. Each register is
an 80-byte record of 64-bit fields
    id, address, count (1), data id (= id + 1), address type, data type, operation, ...
and the data id leads, through a table of {offset, 0, id, "registerData"} entries,
to a 16-byte {value, delay in microseconds} in a pool. The pool's start is found by
where the init sequence's first values line up (0x4000, 0x4000, ... 0x0001 for 0x6010).
"""
import re
import struct
import sys


def tables(path):
    b = open(path, 'rb').read()
    q = lambda o: struct.unpack_from('<Q', b, o)[0]
    u = lambda o: struct.unpack_from('<I', b, o)[0]
    pool = {}
    for m in re.finditer(rb'registerData\x00', b):
        s = m.start() - 24
        if s >= 0:
            pool[q(s + 16)] = q(s)

    def isrec(o):
        if o + 0x50 > len(b):
            return False
        rid, addr, cnt, did, at, dt, op = [q(o + 8 * k) for k in range(7)]
        return (0x100 < rid < 0x100000 and did == rid + 1 and cnt == 1 and at in (1, 2) and
                dt in (1, 2) and op < 8 and addr < 0x10000 and did in pool)

    runs, o = [], 0
    while o < len(b) - 0x50:
        if isrec(o):
            start = o
            while isrec(o):
                o += 0x50
            runs.append([(q(r + 8), q(r + 24), q(r + 48)) for r in range(start, o, 0x50)])
        else:
            o += 8
    # the pool's base: where the init sequence's first values line up
    init = next(r for r in runs if [a for a, _, _ in r[:2]] == [0xfcfc, 0x6028])
    base = None
    for x in range(0, len(b) - 4, 4):
        if u(x) == 0x4000:
            c = x - pool[init[0][1]]
            if all(0 <= c + pool[d] < len(b) - 16 for _, d, _ in init[:5]) and \
                    u(c + pool[init[1][1]]) == 0x4000 and u(c + pool[init[4][1]]) == 1:
                base = c
                break
    if base is None:
        sys.exit("gen-tables: the data pool was not found")
    out = []
    for r in runs:
        if any(op != 0 for _, _, op in r):
            continue		# not only writes (a read, a poll)
        out.append([(addr, q(base + pool[did]), q(base + pool[did] + 8)) for addr, did, _ in r])
    return out


def emit(name, rows, note=""):
    print("static const struct s5kgw1_reg s5kgw1_%s[] = {%s" % (name, note))
    for addr, val, delay in rows:
        if val > 0xffff:
            sys.exit("gen-tables: 0x%x is not 16-bit, at 0x%04x" % (val, addr))
        print("\t{ 0x%04x, 0x%04x }," % (addr, val))
        if delay:
            print("\t{ S5KGW1_DELAY, %d }," % ((delay + 999) // 1000))
    print("};\n")


def main():
    runs = tables(sys.argv[1])

    def find(pred, what):
        for r in runs:
            if pred(dict((a, v) for a, v, _ in r), len(r)):
                return r
        sys.exit("gen-tables: no %s" % what)

    init = find(lambda d, n: 0x6010 in d and 0xfcfc in d and n > 50, "init list")
    full = find(lambda d, n: d.get(0x034c) == 4640 and d.get(0x034e) == 3472 and d.get(0x0310) == 0x157,
                "4640x3472 at 30 fps")
    small = find(lambda d, n: d.get(0x034c) == 2320 and d.get(0x034e) == 1736, "2320x1736")
    hd = find(lambda d, n: d.get(0x034c) == 1920 and d.get(0x034e) == 1080 and d.get(0x0312) == 2,
              "1920x1080 at 120 fps")
    start = find(lambda d, n: d.get(0x0100) == 0x0100 and 0x6214 in d and n < 8, "stream on list")
    print("/* SPDX-License-Identifier: GPL-2.0 */")
    print("/* Generated by gen-tables.py from Xiaomi's com.qti.sensormodule.*_s5kgw1.bin; do not edit */\n")
    emit("init", init)
    emit("mode_4640x3472", full, "\t/* 30 fps, MIPI 2195.2 Mbps a lane */")
    emit("mode_2320x1736", small, "\t/* 60 fps, MIPI 1740.8 Mbps a lane */")
    emit("mode_1920x1080", hd, "\t/* 120 fps, MIPI 1318.4 Mbps a lane */")
    emit("stream_on", start)


main()
